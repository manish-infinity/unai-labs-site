#!/usr/bin/env bash
# Build the Code Snippets body (no opening <?php tag) from the tested engine + WordPress glue.
set -euo pipefail
cd "$(dirname "$0")"
out=../snippets/ambassador-ledger.php
{
  echo '<?php'
  echo '/* GENERATED by tools/ambassador/build-snippet.sh from ledger.php (engine, unit-tested) + wp-glue.php. Do not edit by hand. */'
  sed -e '1{/^<?php/d}' -e '/^declare(strict_types=1);/d' ledger.php
  cat wp-glue.php
} > "$out"
php -l "$out"
echo "built $out"
